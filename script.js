const select = document.getElementById("languageSelect");
const year = document.getElementById("year");
year.textContent = new Date().getFullYear();

function setLanguage(lang) {
  const t = translations[lang] || translations.ja;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  select.value = lang;
  localStorage.setItem("quicklessonLang", lang);

  const titles = {
    ja: "QuickLesson | 5分から話せる語学練習",
    en: "QuickLesson | Language speaking practice in 5 minutes",
    fr: "QuickLesson | Pratiquez une langue dès 5 minutes",
    es: "QuickLesson | Practica idiomas desde 5 minutos"
  };
  document.title = titles[lang] || titles.ja;
}

const stored = localStorage.getItem("quicklessonLang");
const browserLang = navigator.language.slice(0,2);
const initial = stored || (translations[browserLang] ? browserLang : "ja");
setLanguage(initial);

select.addEventListener("change", e => setLanguage(e.target.value));
